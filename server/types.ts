/** +1 = along the chain's station order, -1 = against it */
export type Direction = 1 | -1;

export type LngLat = [number, number];

export interface NetworkChain {
  loop: boolean;
  stations: string[];
  /** Track geometry. For loops it ends back at the first station. */
  path: LngLat[];
  /** Index into `path` of each station. */
  at: number[];
}

export interface NetworkLine {
  id: string;
  name: string;
  short: string;
  color: string;
  apiIds: string[];
  /** Station name -> display position */
  stations: Record<string, LngLat>;
  chains: NetworkChain[];
}

/** data/network.json, generated by scripts/build-network.ts */
export interface Network {
  generated: string;
  attribution: string;
  lines: NetworkLine[];
}

export interface Train {
  /** `${line}:${trainNo}` */
  id: string;
  line: string;
  chain: number;
  /** Fractional station index along the chain, 0 <= pos < stations.length (+1 more for loops) */
  pos: number;
  dir: Direction;
  /** False while dwelling at a station; the client only extrapolates moving trains. */
  moving: boolean;
  dest?: string;
  express?: boolean;
  /** When the train is due at chain station `station` (epoch ms), if the feed says so. */
  eta?: { station: number; at: number };
}

export interface BoardItem {
  train: string;
  dest?: string;
  express?: boolean;
  /** The feed's own wording, e.g. "2번째 전역 (신도림)", "전역 도착" */
  msg: string;
  /** Arrival time (epoch ms) when known; the client turns it into a live countdown. */
  at?: number;
}

/** Upcoming trains at one station on one line, grouped by direction ("○○방면"). */
export interface Board {
  line: string;
  station: string;
  ts: number;
  groups: { heading: string; items: BoardItem[] }[];
}

export interface Arrival {
  line: string;
  chain: number;
  station: number;
  dir: Direction;
}

export interface Snapshot {
  source: "live" | "mock";
  ts: number;
  /** How long until the next snapshot, so the client can pace animation and sounds. */
  intervalMs: number;
  /** Lines that currently have realtime data (live) or are simulated (mock). */
  lines: string[];
  /** True between 01:00 and 05:30 KST when live polling is paused. */
  paused?: boolean;
  trains: Train[];
  arrivals: Arrival[];
}

export interface Feed {
  readonly source: Snapshot["source"];
  /** Returns the next snapshot; called on every tick. */
  next(): Promise<Snapshot>;
  /** Upcoming trains at a station, from data the feed already has. */
  board(line: string, station: string): Board | undefined;
  intervalMs: number;
}
